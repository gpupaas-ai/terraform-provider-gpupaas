package brand_test

import (
	"reflect"
	"runtime"
	"strings"
	"testing"

	"github.com/hashicorp/terraform-plugin-go/tfprotov6"

	"github.com/gpupaas-ai/terraform-provider-gpupaas/internal/brand"
)

// Every method of the plugin protocol whose response carries text a user can read must be wrapped, or that
// text leaks the official identity. When a Terraform protocol upgrade adds such a method, this test fails until
// the wrapper handles it.
func TestServerWrapsEveryMethodThatCarriesText(t *testing.T) {
	diagnostics := reflect.TypeOf([]*tfprotov6.Diagnostic(nil))
	iface := reflect.TypeOf((*tfprotov6.ProviderServer)(nil)).Elem()
	srv := reflect.TypeOf(&brand.Server{})
	checked := 0
	for i := 0; i < iface.NumMethod(); i++ {
		m := iface.Method(i)
		if m.Type.NumOut() == 0 {
			continue
		}
		out := m.Type.Out(0)
		for out.Kind() == reflect.Ptr {
			out = out.Elem()
		}
		if out.Kind() != reflect.Struct {
			continue
		}
		carriesText := false
		for j := 0; j < out.NumField(); j++ {
			f := out.Field(j)
			// diagnostics, a function error, a plain error string, or a stream of results (list resources)
			if f.Type == diagnostics || f.Name == "Error" || f.Name == "Results" {
				carriesText = true
			}
		}
		if !carriesText {
			continue
		}
		checked++
		sm, ok := srv.MethodByName(m.Name)
		if !ok {
			t.Errorf("%s is missing from brand.Server", m.Name)
			continue
		}
		pc := sm.Func.Pointer()
		file, _ := runtime.FuncForPC(pc).FileLine(pc)
		// a method promoted from the embedded server is a compiler-generated forwarder, not our wrapper
		if strings.Contains(file, "<autogenerated>") {
			t.Errorf("%s is not wrapped: its text would keep the official identity", m.Name)
		}
	}
	if checked < 20 {
		t.Fatalf("only %d protocol methods inspected; the check itself is broken", checked)
	}
}
